package org.example.dq;

/** Измерение качества данных, к которому относится правило. */
public enum Dimension {
    /** Соответствие объявленной схеме датасета: форматы идентификаторов и типы. */
    SCHEMA,
    /** Заполненность обязательных полей. */
    COMPLETENESS,
    /** Допустимость значения само по себе. */
    VALIDITY,
    /** Согласованность полей между собой. */
    CONSISTENCY,
    /** Отсутствие дублей. */
    UNIQUENESS,
    /** Совпадение со справочником. */
    REFERENCE
}
